export function getMbtiAxisInsight(axis: MbtiAxis, leftPercent: number) {
  const insight = AXIS_INSIGHTS[axis];
  const close = leftPercent >= 45 && leftPercent <= 55;
  const dominant = leftPercent >= 50 ? insight.left : insight.right;
  return {
    title: insight.title,
    left: insight.left,
    right: insight.right,
    close,
    summary: leftPercent === 50
      ? '两端分数相同；这次作答无法区分偏好，换个情境或重测可能出现不同字母。'
      : close
      ? `两种方式你都可能用得上；这次结果略偏${dominant.label}，换个情境或重测可能出现不同字母。`
      : `${leftPercent < 35 || leftPercent > 65 ? '较明显' : '略微'}偏向${dominant.label}：${dominant.description}。另一侧并不是你的弱项。`,
  };
}
